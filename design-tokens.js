/**
 * Tailwind's stock hues, re-pointed at the iOS ramps.
 *
 * `blue`/`green`/`orange`/`red` were already semantically right and only off
 * brand, so re-pointing them is invisible at the call site: the source still
 * reads `bg-green-100` and now renders iOS green.
 *
 * `yellow`, `amber`, `emerald`, `sky` and `cyan` are aliases onto the hue that
 * carries the same meaning in this system — there is no separate "amber" state,
 * it is a warning, and warnings are orange here.
 *
 * Deliberately NOT aliased: `purple`, `indigo`, `violet`, `fuchsia`, `pink`.
 * Those have no meaning in this design system, so they are removed from the
 * source instead of being silently re-pointed — aliasing them would leave the
 * markup saying "purple" while the screen showed teal, which is worse than the
 * drift it replaces.
 */
export const tailwindHueOverrides = {
  blue: RAMPS.blue,
  sky: RAMPS.blue,
  green: RAMPS.green,
  emerald: RAMPS.green,
  orange: RAMPS.orange,
  amber: RAMPS.orange,
  yellow: RAMPS.orange,
  red: RAMPS.red,
  teal: RAMPS.teal,
  cyan: RAMPS.teal,
};

