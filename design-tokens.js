/**
 * Shared design tokens — the single source of truth for colour across all five
 * Vite apps. Every app's `tailwind.config.js` imports from here, so a hue is
 * defined once and cannot drift between admin, customer, kitchen, portal and
 * onboarding.
 *
 * The values come from DESIGN.md ("Apple-Native Soft Minimalism") and
 * docs/UIUX-design-system.md. Do not add a colour here without adding it to
 * DESIGN.md too — an undocumented token is drift with extra steps.
 *
 * Each semantic hue is a three-step ramp rather than a single value:
 *
 *   soft     tinted background for badges, stat tiles and hover states
 *   DEFAULT  the iOS system colour — fills, dots, bars, icons on white
 *   deep     text and icons sitting *on* the soft tint (AA at normal size)
 *
 * The ramp exists because the pattern it replaces was `bg-<hue>-100` plus
 * `text-<hue>-700`, and collapsing that to one flat token would have put
 * mid-saturation text on a pale tint at roughly 2:1. `soft`/`deep` pairs all
 * clear 4.5:1:
 *
 *   ios-blue-deep   on ios-blue-soft    6.5:1
 *   ios-green-deep  on ios-green-soft   5.9:1
 *   ios-orange-deep on ios-orange-soft  5.2:1
 *   ios-red-deep    on ios-red-soft     5.8:1
 *   ios-teal-deep   on ios-teal-soft    5.0:1
 *
 * `soft` for blue and orange are the `badge-blue-soft` / `badge-orange-soft`
 * already named in DESIGN.md; green, red and teal extend that pattern. The
 * `deep` values are the "ink" variants already used by
 * docs/architecture/master-user-flow.html, so they are the project's existing
 * darker tones rather than newly invented ones.
 */

