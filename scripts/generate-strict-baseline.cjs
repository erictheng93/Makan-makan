#!/usr/bin/env node

/**
 * Generate a single STRICT baseline migration from an existing migration
 * track.
 *
 * Why replay-and-dump rather than regenerating from the Drizzle schema:
 * `sqlite_master` holds the DDL that is actually in effect, and this schema
 * has a lot that Drizzle does not know about — 93 triggers (the
 * `*_restaurant_guard_bi/bu` tenant guards), 15 partial indexes, and CHECK
 * constraints, all added by hand-written migrations. Anything regenerated
 * from `packages/database/src/schema/` would silently drop them. Replaying
 * the track and dumping the result cannot, because it copies the live DDL
 * verbatim.
 *
 * Only `CREATE TABLE` statements are rewritten, by appending the STRICT
 * table-option. Indexes and triggers are emitted unchanged.
 *
 * Usage:
 *   node scripts/generate-strict-baseline.cjs [--track <dir>] [--out <file>]
 *
 * With no --out the SQL goes to stdout. The output is deliberately not
 * checked in: it is a build product of the track it was generated from, and
 * `tests/unit/generate-strict-baseline.test.ts` proves it round-trips.
 */

const fs = require("node:fs");
const path = require("node:path");
const { findMatchingParen } = require("./check-strict-tables.cjs");

const DEFAULT_TRACK = "packages/database/migrations_fresh";
const SEPARATOR = ";\n--> statement-breakpoint\n";

function stripLineComments(sql) {
  return sql
    .split("\n")
    .map((line) => line.replace(/^\s*--.*$/, ""))
    .join("\n");
}

/**
 * Apply every migration in `dir` to a fresh in-memory database and return it.
 * Foreign keys stay off: we are reconstructing DDL, and the track contains
 * table rebuilds whose intermediate states do not satisfy every constraint.
 */
function replayTrack(dir, Database) {
  const db = new Database(":memory:");
  db.pragma("foreign_keys = OFF");
  const failures = [];

  for (const file of fs
    .readdirSync(dir)
    .filter((f) => f.endsWith(".sql"))
    .sort()) {
    const sql = fs.readFileSync(path.join(dir, file), "utf8");
    for (const statement of sql.split(/--> statement-breakpoint/)) {
      const trimmed = stripLineComments(statement).trim();
      if (!trimmed) continue;
      try {
        db.exec(trimmed);
      } catch (error) {
        failures.push(`${file}: ${error.message}`);
      }
    }
  }

  return { db, failures };
}

/** Append the STRICT table-option to a `CREATE TABLE` statement. */
function addStrict(sql) {
  const open = sql.indexOf("(");
  const close = open === -1 ? -1 : findMatchingParen(sql, open);
  if (close === -1) {
    throw new Error(`cannot locate column list in: ${sql.slice(0, 80)}`);
  }
  const existingOptions = sql.slice(close).replace(/;\s*$/, "").trim();
  // Idempotent: regenerating from an already-STRICT baseline must not
  // produce `) STRICT, STRICT`.
  if (/\bSTRICT\b/i.test(existingOptions)) return sql.replace(/;\s*$/, "");
  // Table options are a comma-separated list, so `) WITHOUT ROWID` has to
  // become `) WITHOUT ROWID, STRICT` rather than `) STRICT WITHOUT ROWID`.
  return existingOptions
    ? `${sql.replace(/;\s*$/, "")}, STRICT`
    : `${sql.slice(0, close)} STRICT`;
}

function collectObjects(db) {
  const rows = db
    .prepare(
      `SELECT type, name, sql FROM sqlite_master
       WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%'
       ORDER BY rowid`,
    )
    .all();

  // fts5 creates its own shadow tables (dish_search_fts_data, _idx, ...).
  // Emitting them would collide with what CREATE VIRTUAL TABLE builds.
  const virtualTables = rows
    .filter((r) => /^CREATE\s+VIRTUAL\s+TABLE/i.test(r.sql))
    .map((r) => r.name);
  const isShadow = (name) =>
    virtualTables.some((vt) => name !== vt && name.startsWith(`${vt}_`));

  return rows.filter((r) => !isShadow(r.name));
}

function generateStrictBaseline(options = {}) {
  const root = options.root ?? process.cwd();
  const Database = options.Database ?? require("better-sqlite3");
  const dir = path.resolve(root, options.track ?? DEFAULT_TRACK);
  const { db, failures } = replayTrack(dir, Database);

  const statements = [];
  const counts = { table: 0, index: 0, trigger: 0, view: 0, virtual: 0 };

  for (const row of collectObjects(db)) {
    const isVirtual = /^CREATE\s+VIRTUAL\s+TABLE/i.test(row.sql);
    if (row.type === "table" && !isVirtual) {
      statements.push(addStrict(row.sql));
      counts.table++;
    } else {
      statements.push(row.sql.replace(/;\s*$/, ""));
      if (isVirtual) counts.virtual++;
      else counts[row.type] = (counts[row.type] ?? 0) + 1;
    }
  }

  db.close();

  const header = [
    "-- STRICT baseline.",
    `-- Generated by scripts/generate-strict-baseline.cjs from ${options.track ?? DEFAULT_TRACK}.`,
    "-- Every non-virtual table carries the STRICT table-option so SQLite",
    "-- rejects TEXT written into an INTEGER column instead of storing it.",
    "-- Do not hand-edit: regenerate, or make the change in a later migration.",
    "",
  ].join("\n");

  return {
    sql: `${header}${statements.join(SEPARATOR)};\n`,
    counts,
    failures,
  };
}

if (require.main === module) {
  const argv = process.argv.slice(2);
  const readFlag = (name) => {
    const i = argv.indexOf(name);
    return i === -1 ? undefined : argv[i + 1];
  };

  const result = generateStrictBaseline({ track: readFlag("--track") });

  if (result.failures.length > 0) {
    console.error(
      `Refusing to generate: ${result.failures.length} statement(s) failed while replaying the track.`,
    );
    for (const failure of result.failures.slice(0, 20)) {
      console.error(`- ${failure}`);
    }
    console.error(
      "A track that cannot replay from empty cannot produce a trustworthy baseline.",
    );
    process.exit(1);
  }

  const out = readFlag("--out");
  if (out) {
    fs.writeFileSync(out, result.sql);
    console.error(
      `Wrote ${out} (${Math.round(result.sql.length / 1024)} KB): ` +
        `${result.counts.table} STRICT tables, ${result.counts.virtual} virtual, ` +
        `${result.counts.index} indexes, ${result.counts.trigger} triggers.`,
    );
  } else {
    process.stdout.write(result.sql);
  }
}

module.exports = { generateStrictBaseline, addStrict, replayTrack };
